"""Export a tidy star schema to outputs/powerbi/ for Power BI, plus reports/dashboard_reconciliation.md.
Reads only pipeline outputs and data/processed/sales_clean.csv; every number comes from those files."""
import pandas as pd

from src import config as C

SNAP_COLS = {"CA": "snap_ca", "TX": "snap_tx", "WI": "snap_wi"}


def _write(df: pd.DataFrame, name: str) -> pd.DataFrame:
    """Round floats to 3 decimals and write a compact CSV (dates are already ISO strings)."""
    df = df.round(3)
    df.to_csv(C.POWERBI_DIR / name, index=False)
    print(f"[export_powerbi] {name}: {len(df):,} rows x {df.shape[1]} cols")
    return df


def build_dim_sku_location(sales: pd.DataFrame) -> pd.DataFrame:
    last = sales.sort_values("date").groupby("series_id").last()
    dim = pd.DataFrame({"series_id": last.index, "sku": last["item_id"].to_numpy(), "location": last["store_id"].to_numpy(),
                        "state": last["state_id"].to_numpy(), "latest_price": last["sell_price"].to_numpy()})
    dim["lead_time"] = dim["location"].map(C.LEAD_TIME_DAYS)  # ASSUMPTION from config
    return dim[["series_id", "sku", "location", "state", "lead_time", "latest_price"]]


def build_dim_date(sales: pd.DataFrame, last_forecast_date: str) -> pd.DataFrame:
    """One row per day from history start to the end of the forecast horizon. Event/SNAP info exists only for observed days."""
    cal = sales.groupby("date").agg(event_name=("event_name_1", "first")).reset_index()
    snap = sales.pivot_table(index="date", columns="state_id", values="snap", aggfunc="max").rename(columns=SNAP_COLS).reset_index()
    d = pd.DataFrame({"date": pd.date_range(sales["date"].min(), last_forecast_date)})
    d = d.merge(cal, on="date", how="left").merge(snap, on="date", how="left")
    d["year"], d["month"] = d["date"].dt.year, d["date"].dt.month
    d["year_month"] = d["date"].dt.strftime("%Y-%m")
    d["week_start"] = (d["date"] - pd.to_timedelta(d["date"].dt.weekday, unit="D")).dt.strftime("%Y-%m-%d")  # Monday
    d["weekday"] = d["date"].dt.day_name()
    d["weekday_num"] = d["date"].dt.weekday + 1  # Monday = 1 ... Sunday = 7
    d["is_event"] = d["event_name"].notna().astype(int)
    d["date"] = d["date"].dt.strftime("%Y-%m-%d")
    snap_cols = list(SNAP_COLS.values())
    d[snap_cols] = d[snap_cols].astype("Int64")  # blank for future days (calendar not available there)
    return d[["date", "year", "month", "year_month", "week_start", "weekday", "weekday_num", "is_event", "event_name"] + snap_cols]


def build_fact_sales(sales: pd.DataFrame) -> pd.DataFrame:
    f = sales[["date", "series_id", "units", "revenue", "likely_stockout", "is_outlier"]].copy()
    f["date"] = f["date"].dt.strftime("%Y-%m-%d")
    f[["likely_stockout", "is_outlier"]] = f[["likely_stockout", "is_outlier"]].astype(int)  # 1 = flagged
    return f


def build_fact_forecast() -> pd.DataFrame:
    """Selected model: 3 backtest folds (actuals + error) and the 28-day future forecast (no actuals, so no error)."""
    f = pd.read_csv(C.OUTPUT_DIR / "forecasts.csv")
    f["error"] = f["forecast_demand"] - f["actual_demand"]  # positive = over-forecast (same sign as backtest_forecasts.csv)
    f["abs_error"] = f["error"].abs()
    f["fold"] = f["fold"].astype("Int64")  # blank for future rows
    return f[["date", "series_id", "fold", "forecast_type", "model_used", "actual_demand", "forecast_demand", "error", "abs_error"]]


def build_fact_backtest() -> pd.DataFrame:
    b = pd.read_csv(C.OUTPUT_DIR / "backtest_forecasts.csv")
    return b[["date", "fold", "series_id", "model", "actual_demand", "forecast_demand", "error", "abs_error"]]


def write_reconciliation(sales: pd.DataFrame, mc: pd.DataFrame, rl: pd.DataFrame) -> None:
    """reports/dashboard_reconciliation.md: the KPI values the dashboards must show (computed from the exported files)."""
    sel = mc[mc["selected"]].iloc[0]
    todo = rl[rl["recommended_order_quantity"] > 0]
    by_loc = rl.groupby("location").agg(reorder=("recommended_order_quantity", lambda s: int((s > 0).sum())),
                                        units=("recommended_order_quantity", "sum"), value=("order_value", "sum"),
                                        high=("stockout_risk", lambda s: int((s == "HIGH").sum())))
    L = ["# Dashboard reconciliation", "",
         "Expected KPI values. The Power BI report and the Streamlit app must show exactly these numbers.",
         "Generated by `src/export_powerbi.py` from `outputs/powerbi/*.csv`; do not edit by hand.", "",
         "## Demand (Page 1)", "",
         "| KPI | Value |", "|---|---|",
         f"| Total units | {int(sales['units'].sum()):,} |",
         f"| Total revenue | ${sales['revenue'].sum():,.2f} |",
         f"| Date range | {sales['date'].min():%Y-%m-%d} to {sales['date'].max():%Y-%m-%d} ({sales['date'].nunique()} days) |",
         f"| Series (SKU-locations) | {sales['series_id'].nunique()} |", "",
         "## Forecast performance (Page 2)", "",
         "| KPI | Value |", "|---|---|",
         f"| Selected model | {sel['model']} |",
         f"| MAE | {sel['MAE']:.3f} |", f"| RMSE | {sel['RMSE']:.3f} |", f"| WAPE | {sel['WAPE']:.1%} |", "",
         "## Inventory reorder engine (Page 3), run date " + C.RUN_DATE, "",
         "| KPI | Value |", "|---|---|",
         f"| SKU-locations to reorder today | {len(todo)} of {len(rl)} |",
         f"| Total recommended units | {int(todo['recommended_order_quantity'].sum()):,} |",
         f"| Total order value | ${todo['order_value'].sum():,.2f} |",
         f"| HIGH-risk SKU-locations | {int((rl['stockout_risk'] == 'HIGH').sum())} |", "",
         "### By location", "",
         "| Location | SKU-locations to reorder | Units | Order value | HIGH risk |", "|---|---|---|---|---|"]
    L += [f"| {loc} | {int(r['reorder'])} | {int(r['units']):,} | ${r['value']:,.2f} | {int(r['high'])} |" for loc, r in by_loc.iterrows()]
    L += ["", "Notes: current inventory is SYNTHETIC (M5 has no inventory data). Revenue = units x sell price. "
          "Units include the Christmas-day imputed values (flagged `is_imputed` upstream)."]
    (C.ROOT / "reports").mkdir(exist_ok=True)
    (C.ROOT / "reports" / "dashboard_reconciliation.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("[export_powerbi] wrote reports/dashboard_reconciliation.md")


def main() -> None:
    C.POWERBI_DIR.mkdir(parents=True, exist_ok=True)
    sales = pd.read_csv(C.SALES_CLEAN_PATH, parse_dates=["date"])
    ff = _write(build_fact_forecast(), "fact_forecast.csv")
    _write(build_dim_sku_location(sales), "dim_sku_location.csv")
    _write(build_dim_date(sales, ff["date"].max()), "dim_date.csv")
    _write(build_fact_sales(sales), "fact_sales_daily.csv")
    _write(build_fact_backtest(), "fact_backtest_all_models.csv")
    mc = _write(pd.read_csv(C.OUTPUT_DIR / "model_comparison.csv"), "model_comparison.csv")
    rl = _write(pd.read_csv(C.OUTPUT_DIR / "reorder_list.csv"), "reorder_list.csv")
    _write(pd.read_csv(C.OUTPUT_DIR / "policy_simulation.csv"), "policy_simulation.csv")
    write_reconciliation(sales, mc, rl)
    size = sum(p.stat().st_size for p in C.POWERBI_DIR.glob("*.csv"))
    print(f"[export_powerbi] outputs/powerbi total size: {size / 1e6:.2f} MB")


if __name__ == "__main__":
    main()
